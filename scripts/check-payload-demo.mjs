import { chromium, expect } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const base = process.env.PAYLOAD_PREVIEW_URL || 'http://kit.localhost:5184';
const env = Object.fromEntries((await readFile(new URL('../examples/payload-dashboard/app/.env', import.meta.url), 'utf8')).split('\n').filter(line => line.includes('=')).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
if (!env.PAYLOAD_DEMO_EMAIL || !env.PAYLOAD_DEMO_PASSWORD) throw Error('Local demo credentials are missing; run the Payload setup first.');
const output = new URL('../test-results/payload/', import.meta.url).pathname;
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const anonymous = await browser.newContext();
  expect((await anonymous.request.get(`${base}/api/notes`)).status()).toBe(403);
  await anonymous.close();
  await page.goto(`${base}/admin`);
  await page.locator('#field-username').fill(env.PAYLOAD_DEMO_USERNAME || 'admin');
  await page.locator('#field-password').fill(env.PAYLOAD_DEMO_PASSWORD);
  if (page.url().includes('create-first-user')) {
    await page.locator('#field-email').fill(env.PAYLOAD_DEMO_EMAIL);
    await page.locator('#field-confirm-password').fill(env.PAYLOAD_DEMO_PASSWORD);
    await page.locator('#field-confirm-password').blur();
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: 'Create', exact: true }).click();
  } else await page.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page.getByRole('link', { name: '演示记录', exact: true }).first()).toBeVisible({ timeout: 15000 });
  console.log('Native admin login passed.');
  const create = await page.request.post(`${base}/api/notes`, { data: { title: '真实 D1 验证', status: 'draft', body: '数据由 Payload 写入本地 D1。' } });
  expect(create.status()).toBe(201);
  const record = (await create.json()).doc;
  const update = await page.request.patch(`${base}/api/notes/${record.id}`, { data: { status: 'published' } });
  expect(update.status()).toBe(200);
  expect((await update.json()).doc.status).toBe('published');
  await page.goto(`${base}/admin/collections/notes/${record.id}`);
  await expect(page.locator('#field-title')).toHaveValue('真实 D1 验证');
  await page.reload();
  await expect(page.locator('#field-title')).toHaveValue('真实 D1 验证');
  await page.screenshot({ path: output + 'note-desktop.png' });
  const png = await readFile(new URL('../examples/payload-dashboard/fixtures/sample.png', import.meta.url));
  const upload = await page.request.post(`${base}/api/media`, { multipart: { _payload: JSON.stringify({ alt: 'WorkerKit 本地上传验证' }), file: { name: 'workerkit-local-demo.png', mimeType: 'image/png', buffer: png } } });
  expect(upload.status()).toBe(201);
  const media = (await upload.json()).doc;
  const downloaded = await page.request.get(new URL(media.url, base).href);
  expect(downloaded.status()).toBe(200);
  expect(Buffer.compare(await downloaded.body(), png)).toBe(0);
  console.log('D1 create/update/read after reload and R2 upload/download passed.');
  const temporary = await page.request.post(`${base}/api/notes`, { data: { title: '删除验证', status: 'draft' } });
  const temporaryId = (await temporary.json()).doc.id;
  expect((await page.request.delete(`${base}/api/notes/${temporaryId}`)).status()).toBe(200);
  expect((await page.request.get(`${base}/api/notes/${temporaryId}`)).status()).toBe(404);
  await page.goto(`${base}/admin`);
  await page.screenshot({ path: output + 'admin-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'WorkerKit 运行台' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: output + 'admin-phone.png' });
  expect(errors).toEqual([]);
  await writeFile(output + 'functional-result.json', JSON.stringify({ runtime: 'workerd (Wrangler local)', auth: true, anonymousNotesDenied: true, d1Crud: true, reloadPersistence: true, r2RoundTripBytes: png.length, mobile: true }, null, 2));
  await page.request.delete(`${base}/api/notes/${record.id}`);
  await page.request.delete(`${base}/api/media/${media.id}`);
  console.log('CRUD deletion, mobile admin and browser error checks passed.');
} catch (error) { console.error(String(error.message).replaceAll(env.PAYLOAD_DEMO_PASSWORD, '[redacted]')); process.exitCode = 1; } finally { await browser.close(); }
