import type { FrameworkEnv } from '../fullstack-shared/backend';
import { createRequestHandler, RouterContextProvider } from 'react-router'; // @ts-ignore Generated by the upstream build.
import * as build from './build/server/index.js';
const handle = createRequestHandler(build, 'production');
export default {
  fetch(request, env, ctx) {
    const context = new RouterContextProvider();
    context.set(build.routes.root.module.handle.cloudflareContext, {
      env,
      ctx,
    });
    return handle(request, context);
  },
} satisfies ExportedHandler<FrameworkEnv>;
