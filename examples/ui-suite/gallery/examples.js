export function describeComponent(path) {
  const cleanPath = path.replace(/\/$/, '');
  const slug = cleanPath
    .split('/')
    .at(-1)
    .replace(/^react-/, '');
  const kind = Object.keys(aliases).find((key) =>
    aliases[key].some((alias) => alias === slug || alias === cleanPath),
  );
  const group =
    Object.keys(groups).find((key) =>
      groups[key].test(kind?.toLowerCase() ?? slug),
    ) ?? '其他';
  return { kind, label: labels[kind], group };
}

