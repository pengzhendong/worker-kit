import { cp, mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';

/** A complete Nuxt application; no CMS or second Worker is generated. */
export async function prepareHubProject({ kit, project, put, snapshot }) {
  const source = path.join(kit, 'examples/nuxthub-dashboard/app');
  await snapshot(kit, path.join(project, 'vendor/worker-kit'), 'nuxt');
  await cp(source, project, {
    recursive: true,
    filter(file) {
      const relative = path.relative(source, file).replaceAll(path.sep, '/');
      return !relative
        .split('/')
        .some((part) =>
          [
            'node_modules',
            '.nuxt',
            '.output',
            '.wrangler',
            '.data',
            '.git',
            'package-lock.json',
            '.env',
            '.dev.vars',
          ].includes(part),
        );
    },
  });
  const pkg = JSON.parse(
    await readFile(path.join(source, 'package.json'), 'utf8'),
  );
  pkg.overrides = {
    tailwindcss: '4.3.4',
    '@tailwindcss/vite': '4.3.4',
    '@tailwindcss/node': '4.3.4',
    '@tailwindcss/oxide': '4.3.4',
  };
  pkg.name = path
    .basename(project)
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-');
  pkg.dependencies['@pengzhendong/worker-kit'] = 'file:vendor/worker-kit';
  Object.assign(pkg.dependencies, {
    '@scalar/api-reference': '1.75.1',
    'openapi-types': '12.1.3',
    agents: '0.32.0',
    'cron-schedule': '6.0.0',
  });
  pkg.devDependencies.vite = '8.3.5';
  pkg.scripts = {
    setup: 'node scripts/project.mjs setup',
    build: 'node scripts/project.mjs build',
    dev: 'node scripts/project.mjs dev',
    check: 'node scripts/project.mjs check',
    'kit:sync': 'node vendor/worker-kit/src/tooling/cli.mjs sync .',
    'kit:rollback': 'node vendor/worker-kit/src/tooling/cli.mjs rollback .',
  };
  await put(path.join(project, 'package.json'), pkg);
  await mkdir(path.join(project, 'shared/ui'), { recursive: true });
  for (const file of [
    'operations.js',
    'operations.d.ts',
    'NuxtWorkspace.vue',
    'ManagementNuxt.vue',
  ]) {
    const text = await readFile(
      path.join(kit, 'examples/ui-demo', file),
      'utf8',
    );
    await put(
      path.join(project, 'shared/ui', file),
      text.replaceAll('../../src/', '../../vendor/worker-kit/src/'),
    );
  }
  await mkdir(path.join(project, 'scripts'), { recursive: true });
  await cp(
    path.join(kit, 'examples/ui-demo/reference.ts'),
    path.join(project, 'scripts/reference.ts'),
  );
  const appFile = path.join(project, 'app/app.vue');
  const app = (await readFile(appFile, 'utf8'))
    .replace('../../../ui-demo/', '../shared/ui/')
    .replace(
      /<UButton\s+to="\/"\s+external[^>]*>返回 (?:WorkerKit|方案选择)<\/UButton>/g,
      '',
    );
  await put(appFile, app);
  await put(
    path.join(project, '.dev.vars.example'),
    'HUB_ADMIN_PASSWORD=password\n',
  );
  const native = JSON.parse(
    await readFile(
      path.join(kit, 'examples/native-dashboard/wrangler.jsonc'),
      'utf8',
    ),
  );
  const config = JSON.parse(
    await readFile(
      path.join(kit, 'examples/payload-dashboard/app/wrangler.jsonc'),
      'utf8',
    ),
  );
  await put(path.join(project, 'wrangler.jsonc'), {
    name: pkg.name,
    main: 'worker.ts',
    compatibility_date: config.compatibility_date,
    compatibility_flags: config.compatibility_flags,
    assets: {
      directory: '.output/public',
      binding: 'ASSETS',
      html_handling: 'none',
      not_found_handling: 'none',
      run_worker_first: [
        '/',
        '/hub',
        '/hub/*',
        '!/hub/_nuxt/*',
        '/management-assets/*',
      ],
    },
    kv_namespaces: config.kv_namespaces.filter((item) =>
      ['NATIVE_STORE', 'KV', 'CACHE'].includes(item.binding),
    ),
    d1_databases: config.d1_databases
      .filter((item) => item.binding === 'DB')
      .map((item) => ({
        ...item,
        migrations_dir: 'server/db/migrations/sqlite',
      })),
    r2_buckets: config.r2_buckets.filter((item) => item.binding === 'BLOB'),
    ratelimits: native.ratelimits,
    durable_objects: {
      bindings: [{ name: 'TASKS', class_name: 'WorkerKitHubTasks' }],
    },
    migrations: [{ tag: 'v1', new_sqlite_classes: ['WorkerKitHubTasks'] }],
  });
  await put(
    path.join(project, 'worker.ts'),
    `import { readBytesLimited } from '@pengzhendong/worker-kit/http';\n// @ts-ignore Generated by Nuxt.\nimport hub from './.output/server/index.mjs';\nexport { WorkerKitHubTasks } from './tasks';\nexport default { async fetch(request: Request, env: object, ctx: ExecutionContext) {\n  const url = new URL(request.url);\n  if (url.pathname === '/' || url.pathname === '/hub') return Response.redirect(new URL('/hub/', url), 308);\n  if (url.pathname.startsWith('/management-assets/')) { const assets = (env as { ASSETS: Fetcher }).ASSETS; const response = await assets.fetch(request); if(response.status !== 404) return response; url.pathname = '/hub' + url.pathname; return assets.fetch(new Request(url,request)); }\n  if (!['GET','HEAD','OPTIONS'].includes(request.method)) {\n    try { const bytes = await readBytesLimited(request.body, 16384, request.signal); request = new Request(request, { body: bytes.slice().buffer as ArrayBuffer }); }\n    catch { return Response.json({error:{code:'body_too_large',message:'请求内容过大或不可读取'}},{status:413}); }\n  }\n  return hub.fetch(request, env, ctx);\n} } satisfies ExportedHandler;\n`,
  );
  await put(
    path.join(project, 'tasks.ts'),
    `import { createTaskWorker } from '@pengzhendong/worker-kit/task-worker';\nimport { runHealthChecks } from '@pengzhendong/worker-kit/runtime';\nimport type { HubEnv } from './server/utils/admin';\nexport class WorkerKitHubTasks extends createTaskWorker<HubEnv>({ backends:['hub'], definitions: env => ({ 'check-bindings': { label:'依赖检查',target:'cloudflare',fields:[],async run(_inputs,{report}) { const checks=[{name:'D1',check:()=>env.DB.prepare('SELECT 1').first()},{name:'KV',check:()=>env.KV.get('__health__')},{name:'R2',check:()=>env.BLOB.head('__health__')}];report({completed:0,total:checks.length,message:'检查依赖'});const result=await runHealthChecks(checks);if(!result.ok)throw new Error('Dependency check failed');report({completed:checks.length,total:checks.length,message:'依赖正常'});return {state:'succeeded',output:{logs:result.checks.map(check=>check.name+': '+check.status)}}} } }) }) {}\n`,
  );
  await mkdir(path.join(project, 'scripts'), { recursive: true });
  await cp(
    new URL('./templates/hub-project.mjs', import.meta.url),
    path.join(project, 'scripts/project.mjs'),
  );

  await put(path.join(project, 'workerkit.json'), {
    frontend: 'nuxt',
    backend: 'hub',
    mount: '/hub/',
    source: 'vendor/worker-kit',
  });
  await put(
    path.join(project, '.gitignore'),
    'node_modules/\n.nuxt/\n.output/\n.data/\n.wrangler/\n.dev.vars\n.env\nworker-configuration.d.ts\npublic/management-assets/\nvendor/worker-kit.previous-*/\n',
  );
  await cp(
    path.join(kit, 'examples/nuxthub-dashboard/LICENSE.nuxthub'),
    path.join(project, 'LICENSE.nuxthub'),
  );
  await put(
    path.join(project, 'README.md'),
    '# Nuxt 全栈应用\n\nNuxt UI + NuxtHub + WorkerKit，一个 Cloudflare Worker。默认包含真实运行检查、KV 设置、访问密钥、审计与任务管理，以及独立存储示例。\n\n`npm install` → `npm run setup` → `npm run dev`，打开 http://localhost:8787/hub/ ，本地账号 admin / password。setup 只在本地变量不存在时复制示例，不重置已有凭据。线上部署前配置自己的绑定、域名和 HUB_ADMIN_PASSWORD Secret。\n\napp/ 是应用页面；server/ 是自己的接口、数据库 schema 与迁移；tasks.ts 是业务任务。shared/ui/ 是可修改的起始界面，vendor/worker-kit 是有摘要校验的公共 SDK 快照。kit:sync 不覆盖页面、接口、迁移和部署配置。\n\n更新：`npm run kit:sync -- --source /path/to/reviewed/worker-kit`，然后 npm install 与 npm run check。回滚：`npm run kit:rollback -- --backup worker-kit.previous-TIMESTAMP`，再安装并检查。数据库迁移另行审核，回滚 SDK 不会撤销数据迁移。\n\nNuxtHub 0.10.12 的 package.json 声明 Apache-2.0，随包 LICENSE 为 MIT；本例保留原始文件并记录上游标识差异。\n',
  );
}
