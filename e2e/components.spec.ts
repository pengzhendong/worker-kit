import { test, expect, openDashboard, screenshot } from './fixtures';

test('component list filters, batches and selects files locally', async ({ page }) => {
  await openDashboard(page, 'components');
  const list = page.getByRole('region', { name: '列表与工具栏示例' });
  await list.getByLabel('搜索演示条目', { exact: true }).fill('文档');
  await expect(list.getByRole('row')).toHaveCount(2);
  await expect(list.getByText('文档归档', { exact: true })).toBeVisible();
  await list.getByLabel('搜索演示条目', { exact: true }).fill('');
  await list.getByRole('checkbox').first().check();
  await list.getByRole('button', { name: '批量停用', exact: true }).click();
  await expect(list.getByRole('switch', { checked: false })).toHaveCount(3);
  await list.getByRole('button', { name: '添加示例', exact: true }).click();
  await expect(list.getByText('新增演示条目 4', { exact: true })).toBeVisible();
  await list.getByRole('switch', { name: '新增演示条目 4启用状态', exact: true }).click();
  await expect(list.getByRole('switch', { checked: false })).toHaveCount(4);
  const upload = page.getByRole('region', { name: '文件选择示例' });
  await upload.locator('input[type=file]').setInputFiles({ name: 'gallery-demo.txt', mimeType: 'text/plain', buffer: Buffer.from('local demo') });
  await expect(upload.getByText('gallery-demo.txt', { exact: true })).toBeVisible();
  await upload.getByRole('button', { name: '移除gallery-demo.txt', exact: true }).click();
  await expect(upload.getByText('gallery-demo.txt', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '重置演示', exact: true }).click();
  await expect(list.getByRole('row')).toHaveCount(4);
  await expect(list.getByRole('switch', { checked: true })).toHaveCount(2);
  await expect(upload.getByRole('row')).toHaveCount(2);
});

test('modal validates input, retains failed drafts and saves on retry', async ({ page }) => {
  await openDashboard(page, 'components');
  await page.getByRole('tab', { name: '表单与确认', exact: true }).click();
  await page.getByRole('button', { name: '编辑演示配置', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '编辑演示配置', exact: true });
  await dialog.getByLabel('配置名称', { exact: true }).fill('');
  await dialog.getByLabel('通知邮箱', { exact: true }).fill('not-an-email');
  await dialog.getByRole('button', { name: '保存演示配置', exact: true }).click();
  await expect(dialog.getByText('请输入配置名称', { exact: true })).toBeVisible();
  await expect(dialog.getByText('请输入有效邮箱', { exact: true })).toBeVisible();
  await dialog.getByLabel('配置名称', { exact: true }).fill('每周汇总');
  await dialog.getByLabel('通知邮箱', { exact: true }).fill('weekly@example.com');
  await dialog.getByRole('switch', { name: '模拟保存失败', exact: true }).click();
  await dialog.getByRole('button', { name: '保存演示配置', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('演示保存失败');
  await expect(dialog.getByLabel('配置名称', { exact: true })).toHaveValue('每周汇总');
  await dialog.getByRole('switch', { name: '模拟保存失败', exact: true }).click();
  await dialog.getByRole('button', { name: '保存演示配置', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByText('每周汇总', { exact: true })).toBeVisible();
  await expect(page.getByText('weekly@example.com', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '编辑演示配置', exact: true }).click();
  await dialog.getByLabel('配置名称', { exact: true }).fill('取消的修改');
  await dialog.getByRole('button', { name: /^取\s*消$/ }).click();
  await expect(page.getByText('每周汇总', { exact: true })).toBeVisible();
  await expect(page.getByText('取消的修改', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '删除演示记录', exact: true }).click();
  await page.getByRole('button', { name: /^取\s*消$/ }).click();
  await expect(page.getByText('过期演示记录', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '删除演示记录', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(page.getByText('过期演示记录', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '还原演示记录', exact: true }).click();
  await expect(page.getByText('过期演示记录', { exact: true })).toBeVisible();
});

test('data states recover and feedback controls work', async ({ page }) => {
  await openDashboard(page, 'components');
  await page.getByRole('tab', { name: '状态与反馈', exact: true }).click();
  const preview = page.getByRole('region', { name: '数据状态预览' });
  await page.getByText('空数据', { exact: true }).click();
  await expect(preview.getByText('还没有演示数据', { exact: true })).toBeVisible();
  await preview.getByRole('button', { name: '生成演示数据', exact: true }).click();
  await expect(preview.getByText('示例数据已加载', { exact: true })).toBeVisible();
  await page.getByText('加载', { exact: true }).click();
  await expect(preview).toHaveAttribute('aria-busy', 'true');
  await page.getByText('失败', { exact: true }).click();
  await expect(preview.getByText('演示加载失败', { exact: true })).toBeVisible();
  await preview.getByRole('button', { name: '重试加载', exact: true }).click();
  await expect(preview).toHaveAttribute('aria-busy', 'true');
  await expect(preview.getByText('示例数据已加载', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '成功消息', exact: true }).click();
  await expect(page.getByText('演示操作成功', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '失败消息', exact: true }).click();
  await expect(page.getByText('演示操作失败，请重试', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '打开通知', exact: true }).click();
  await expect(page.getByText('这是一条通知示例，可手动关闭。', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '禁用操作', exact: true })).toBeDisabled();
});

